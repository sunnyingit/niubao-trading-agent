def side_user(view: dict) -> str:
    return json.dumps(view, ensure_ascii=False)


def chief_user(view: dict, arguments: list[dict]) -> str:
    payload = dict(view)
    payload["arguments"] = arguments
    return json.dumps(payload, ensure_ascii=False)
